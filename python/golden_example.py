"""Write the golden loan's month-by-month working into docs/methodology.md.

The table is computed by python/ecl/ecl_math.py (the independent
implementation the golden tests use) and replaces everything between the
<!-- golden:start --> and <!-- golden:end --> markers, so the worked example in
the docs can never drift from the code.

Usage: python python/golden_example.py
"""
from __future__ import annotations

from ecl import ecl_math, markdown
from ecl.config import DOCS_DIR
from ecl.pd import monthly_hazard

B, RATE, N, PD, LGD = 10_000.0, 0.12, 24, 0.05, 0.80
START, END = "<!-- golden:start -->", "<!-- golden:end -->"


def golden_block() -> str:
    months = ecl_math.schedule(B, RATE, N, 12, PD, LGD)
    stage1 = sum(m.loss for m in months)
    stage2 = ecl_math.model_ecl(2, B, RATE, N, PD, LGD)
    rows = [[m.t, f"{m.ead:,.2f}", f"{m.survival:.6f}", f"{m.marginal_pd:.6f}", f"{m.discount:.6f}",
             f"{m.loss:.4f}"] for m in months]
    rows.append(["**Total**", "", "", f"{sum(m.marginal_pd for m in months):.6f}", "", f"**{stage1:.4f}**"])
    finals = []
    for stage, rate in ((1, 0.01), (2, 0.05), (3, 0.40)):
        model = ecl_math.model_ecl(stage, B, RATE, N, PD, LGD)
        floor_amount, final, applied = ecl_math.final_ecl(model, rate, B)
        finals.append([f"Stage {stage}", f"${model:,.2f}", f"{rate:.0%} = ${floor_amount:,.2f}",
                       f"${final:,.2f}" + (" (floor applied)" if applied == "Y" else "")])
    return "\n".join([
        START,
        "",
        f"Inputs: balance ${B:,.0f}, rate {RATE:.0%} a year (r = {RATE / 12:.0%} a month), {N} months left, "
        f"12-month PD {PD:.0%}, LGD {LGD:.0%}, DPD 0, base scenario only.",
        "",
        f"- Level payment P = B r / (1 - (1 + r)^-n) = **${ecl_math.level_payment(B, RATE / 12, N):,.2f}**",
        f"- Monthly hazard h = 1 - (1 - PD_12m)^(1/12) = **{float(monthly_hazard(PD)):.5%}**",
        "",
        "Stage 1, month by month (horizon min(12, n) = 12):",
        "",
        markdown.table(["t", "EAD_t = B_(t-1)", "Survival (1-h)^(t-1)", "Default in month t",
                        "Discount (1+r)^-t", "Discounted loss"], rows, right=[0, 1, 2, 3, 4, 5]),
        "",
        f"Discounted loss = default in month t x LGD x EAD_t x discount. The 12 months sum to "
        f"${stage1:,.2f}; over the full 24 months (Stage 2) the same sum is ${stage2:,.2f}.",
        "",
        markdown.table(["Case", "Model ECL", "Floor", "Final ECL"], finals, right=[1]),
        "",
        "Generated by `python/golden_example.py` from `python/ecl/ecl_math.py`; `tests/test_ecl_golden.py` checks "
        "that the PL/SQL engine (`run_v2` and `run_v1`) reproduces the last table to the cent.",
        "",
        END,
    ])


def main() -> None:
    path = DOCS_DIR / "methodology.md"
    text = path.read_text(encoding="utf-8")
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    path.write_text(head + golden_block() + tail, encoding="utf-8", newline="\n")
    print(f"updated the golden example in {path}")


if __name__ == "__main__":
    main()
