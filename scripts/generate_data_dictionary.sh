#!/usr/bin/env bash
# Generate docs/data_dictionary.md from the comments stored in Oracle.
#
# Reads USER_TAB_COLUMNS and USER_COL_COMMENTS through V_DATA_DICTIONARY. The
# view also takes the external tables' descriptions from EXT_TABLE_DOC,
# because Oracle can't store comments on external tables (ORA-30657, D-011).
# Every table, view and column must have a description: if one is missing,
# the script names it and stops without touching the doc.
#
# Usage: scripts/generate_data_dictionary.sh
# Exit codes: 0 written, 1 a description is missing or a query failed.
source "$(dirname "${BASH_SOURCE[0]}")/lib/common.sh"

OUT="$ROOT_DIR/docs/data_dictionary.md"
# SQL*Plus spools into the mounted logs/ folder; the file goes once read.
TSV_NAME="data_dictionary.tsv"
TSV="$ROOT_DIR/logs/$TSV_NAME"
trap 'rm -f "$TSV" "$OUT.tmp"' EXIT

run_sql ECL db/reports/export_data_dictionary.sql "$TSV_NAME"

undescribed=$(awk -F'\t' '$1 == "T" { t = $3; if ($4 == "") print t }
                          $1 == "C" && $5 == "" { print t "." $2 }' "$TSV")
[[ -z "$undescribed" ]] || die "no description for: $(paste -sd ' ' <<<"$undescribed") (add a COMMENT, then rerun)"

awk -F'\t' '
  function cell(s) { gsub(/\|/, "\\|", s); return s }
  function anchor(s) { return tolower(s) }
  # Read everything first: the contents list comes before the details.
  $1 == "T" { n++; type[n] = $2; name[n] = $3; about[n] = $4; ncol[n] = 0; next }
  $1 == "C" { c = ++ncol[n]; col[n, c] = $2; dtype[n, c] = $3; nulls[n, c] = $4; desc[n, c] = $5 }
  END {
    split("TABLE|EXTERNAL TABLE|VIEW", order, "|")
    title["TABLE"] = "Tables"; title["EXTERNAL TABLE"] = "External tables"; title["VIEW"] = "Views"
    for (i = 1; i <= n; i++) { count[type[i]]++; columns += ncol[i] }

    print "# Data dictionary"
    print ""
    print "Generated by `scripts/generate_data_dictionary.sh` from the comments stored in Oracle:"
    print "`COMMENT ON TABLE` and `COMMENT ON COLUMN`, plus `EXT_TABLE_DOC` for the external tables,"
    print "which Oracle can'\''t comment. Don'\''t edit this file by hand. Change the comment in `db/` and"
    print "run the script again."
    print ""
    printf "%d tables, %d external tables and %d views, with %d columns between them. Every one has a description.\n", \
           count["TABLE"], count["EXTERNAL TABLE"], count["VIEW"], columns

    for (g = 1; g <= 3; g++) {
      print ""; print "## " title[order[g]]; print ""
      print "| Name | Description |"; print "|---|---|"
      for (i = 1; i <= n; i++) if (type[i] == order[g])
        printf "| [%s](#%s) | %s |\n", name[i], anchor(name[i]), cell(about[i])
    }

    for (g = 1; g <= 3; g++) {
      for (i = 1; i <= n; i++) if (type[i] == order[g]) {
        print ""; print "### " name[i]; print ""
        print "*" toupper(substr(type[i], 1, 1)) tolower(substr(type[i], 2)) "*. " about[i]
        print ""
        print "| # | Column | Type | Nullable | Description |"; print "|---:|---|---|---|---|"
        for (c = 1; c <= ncol[i]; c++)
          printf "| %d | `%s` | %s | %s | %s |\n", c, col[i, c], dtype[i, c], \
                 (nulls[i, c] == "Y" ? "yes" : "no"), cell(desc[i, c])
      }
    }
  }' "$TSV" >"$OUT.tmp"
mv "$OUT.tmp" "$OUT"

summary=$(grep -m1 -E '^[0-9]+ tables' "$OUT")
log "wrote docs/data_dictionary.md: ${summary%%.*}"
